/*
========================================
SUBSTRING PROBLEMS
========================================
*/

/*
1. Generate All Substrings

Generate and return all possible substrings.

Input:
"abc"

Output:
[
  "a",
  "ab",
  "abc",
  "b",
  "bc",
  "c"
]

Explanation:
A substring must be contiguous.
*/

/*
2. Count Substrings

Return the total number of substrings.

Input:
"abc"

Output:
6

Explanation:
a, ab, abc, b, bc, c

Formula:
n * (n + 1) / 2
*/

/*
3. Longest Common Substring

Find the longest substring
present in both strings.

Input:
str1 = "abcdef"
str2 = "zcdemf"

Output:
"cde"

Explanation:
"cde" appears in both strings.
*/

/*
4. Longest Repeating Substring

Find the longest substring
that appears more than once.

Input:
"banana"

Output:
"ana"

Explanation:
"ana" appears twice.
*/

/*
5. Longest Substring Without Repeating Characters

Find the length of the longest substring
without repeating characters.

Input:
"abcabcbb"

Output:
3

Explanation:
"abc"
*/

