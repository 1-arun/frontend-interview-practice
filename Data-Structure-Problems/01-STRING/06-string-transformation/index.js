/*
========================================
STRING TRANSFORMATION PROBLEMS
========================================
*/

/*
1. Capitalize First Letter

Capitalize only the first letter
of the string.

Input:
"hello world"

Output:
"Hello world"
*/

/*
2. Capitalize Every Word

Capitalize the first letter
of every word in the sentence.

Input:
"hello world react"

Output:
"Hello World React"
*/

/*
3. snake_case → camelCase

Convert a snake_case string
to camelCase.

Input:
"hello_world_react"

Output:
"helloWorldReact"

Input:
"user_profile_image"

Output:
"userProfileImage"
*/

/*
4. camelCase → snake_case

Convert a camelCase string
to snake_case.

Input:
"helloWorldReact"

Output:
"hello_world_react"

Input:
"userProfileImage"

Output:
"user_profile_image"
*/

/*
5. Toggle Case

Convert uppercase letters to lowercase
and lowercase letters to uppercase.

Input:
"HeLLo WoRLd"

Output:
"hEllO wOrlD"
*/

/*
========================================
BONUS PROBLEMS
========================================
*/

/*
6. kebab-case → camelCase

Input:
"hello-world-react"

Output:
"helloWorldReact"
*/

/*
7. camelCase → kebab-case

Input:
"helloWorldReact"

Output:
"hello-world-react"
*/

/*
8. Convert To Title Case

Capitalize the first letter of every word
and lowercase the remaining letters.

Input:
"hELLo woRLD"

Output:
"Hello World"
*/

/*
9. Convert Sentence To Slug

Rules:
- Lowercase all characters
- Replace spaces with '-'
- Remove special characters

Input:
"Frontend Developer Interview Guide!"

Output:
"frontend-developer-interview-guide"
*/

/*
10. Normalize User Input

Rules:
- Remove extra spaces
- Convert to lowercase
- Trim start/end spaces

Input:
"   HeLLo     WoRLD   "

Output:
"hello world"
*/