/*
========================================
PALINDROME PROBLEMS
========================================
*/

/*
1. Valid Palindrome

Check whether a string is a palindrome.

Input:
"madam"

Output:
true

Input:
"hello"

Output:
false
*/

/*
2. Palindrome Ignoring Case

Check whether a string is a palindrome
without considering uppercase/lowercase.

Input:
"Madam"

Output:
true

Input:
"RaceCar"

Output:
true
*/

/*
3. Palindrome Ignoring Spaces

Check whether a string is a palindrome
while ignoring spaces.

Input:
"nurses run"

Output:
true

Input:
"never odd or even"

Output:
true
*/

/*
4. Valid Palindrome II

You may delete at most one character.

Return true if the string can become
a palindrome after deleting at most one character.

Input:
"abca"

Output:
true

Explanation:
Remove 'c'
=> "aba"

Input:
"abc"

Output:
false
*/

/*
5. Count Palindromic Substrings

Count all palindrome substrings present in the string.

Input:
"aaa"

Output:
6

Explanation:
"a"
"a"
"a"
"aa"
"aa"
"aaa"
*/

