/*
========================================
REVERSE LINKED LIST PATTERN PROBLEMS
========================================
*/

/*
1. Reverse Linked List

Reverse the entire linked list.

Input:
1 -> 2 -> 3 -> 4 -> 5

Output:
5 -> 4 -> 3 -> 2 -> 1
*/

/*
2. Reverse First K Nodes

Reverse only the first K nodes.

Input:
1 -> 2 -> 3 -> 4 -> 5
k = 3

Output:
3 -> 2 -> 1 -> 4 -> 5
*/

/*
3. Reverse Linked List Recursively

Reverse the linked list
using recursion.

Input:
1 -> 2 -> 3

Output:
3 -> 2 -> 1
*/

/*
4. Reverse Sublist

Reverse nodes from position left to right.

Input:
1 -> 2 -> 3 -> 4 -> 5
left = 2
right = 4

Output:
1 -> 4 -> 3 -> 2 -> 5
*/

/*
5. Reverse Nodes In K Group

Reverse every group of k nodes.

Input:
1 -> 2 -> 3 -> 4 -> 5
k = 2

Output:
2 -> 1 -> 4 -> 3 -> 5
*/