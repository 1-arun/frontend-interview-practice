/*
========================================
TWO POINTER ARRAY PROBLEMS
========================================
*/

/*
1. Reverse Array Using Two Pointers

Reverse the array in-place
using left and right pointers.

Input:
[1, 2, 3, 4, 5]

Output:
[5, 4, 3, 2, 1]
*/

/*
2. Check Palindrome Array

Check whether the array
reads the same forward and backward.

Input:
[1, 2, 3, 2, 1]

Output:
true

Input:
[1, 2, 3, 4]

Output:
false
*/

/*
3. Check Palindrome String

Check whether a string
is a palindrome.

Input:
"madam"

Output:
true

Input:
"hello"

Output:
false
*/

/*
4. Move Zeroes To End

Move all zeroes to the end
while maintaining the order
of non-zero elements.

Input:
[0, 1, 0, 3, 12]

Output:
[1, 3, 12, 0, 0]
*/

/*
5. Move Negatives To Left

Move all negative numbers
to the beginning of the array.

Input:
[1, -2, 3, -4, 5]

Output:
[-2, -4, 1, 3, 5]

Order may vary unless specified.
*/

/*
6. Move Positives To Right

Move all positive numbers
to the right side of the array.

Input:
[1, -2, 3, -4, 5]

Output:
[-2, -4, 1, 3, 5]

Order may vary unless specified.
*/

/*
7. Merge Two Sorted Arrays

Merge two sorted arrays
into a single sorted array.

Input:
arr1 = [1, 3, 5]
arr2 = [2, 4, 6]

Output:
[1, 2, 3, 4, 5, 6]
*/

/*
8. Remove Duplicates From Sorted Array

Remove duplicates from a sorted array
and return the unique elements.

Input:
[1, 1, 2, 2, 3, 4, 4]

Output:
[1, 2, 3, 4]
*/

/*
9. Pair With Given Sum (Sorted Array)

Find a pair whose sum equals target.

Input:
arr = [1, 2, 3, 4, 6]
target = 6

Output:
[2, 4]

Explanation:
2 + 4 = 6
*/

/*
10. Count Pairs With Given Sum

Count all pairs whose sum equals target.

Input:
arr = [1, 2, 3, 4, 5]
target = 6

Output:
2

Explanation:
(1,5)
(2,4)
*/
 
