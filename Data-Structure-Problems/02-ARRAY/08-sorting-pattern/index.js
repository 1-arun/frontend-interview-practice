/*
1. Bubble Sort

Sort the array in ascending order
using Bubble Sort.

Input:
[5, 1, 4, 2, 8]

Output:
[1, 2, 4, 5, 8]

Explanation:
Repeatedly swap adjacent elements
if they are in the wrong order.
*/

/*
2. Selection Sort

Sort the array in ascending order
using Selection Sort.

Input:
[64, 25, 12, 22, 11]

Output:
[11, 12, 22, 25, 64]

Explanation:
Select the minimum element
and place it at the correct position.
*/

/*
3. Insertion Sort

Sort the array in ascending order
using Insertion Sort.

Input:
[12, 11, 13, 5, 6]

Output:
[5, 6, 11, 12, 13]

Explanation:
Insert each element into its
correct position in the sorted part.
*/

/*
4. Sort Ascending

Sort the array from smallest
to largest.

Input:
[5, 3, 8, 1]

Output:
[1, 3, 5, 8]
*/

/*
5. Sort Descending

Sort the array from largest
to smallest.

Input:
[5, 3, 8, 1]

Output:
[8, 5, 3, 1]
*/

/*
6. Sort 0s And 1s

Sort an array containing
only 0s and 1s.

Input:
[1, 0, 1, 0, 0, 1]

Output:
[0, 0, 0, 1, 1, 1]
*/

/*
7. Sort Even And Odd Numbers

Place all even numbers first,
followed by odd numbers.

Input:
[5, 2, 8, 1, 3, 4]

Output:
[2, 8, 4, 5, 1, 3]

Order within groups may vary.
*/

/*
8. Sort By Frequency

Sort elements by their frequency
in descending order.

Input:
[4, 5, 6, 5, 4, 3]

Output:
[4, 4, 5, 5, 6, 3]

Explanation:
4 and 5 appear twice.
6 and 3 appear once.
*/

/*
9. Find Kth Largest After Sorting

Return the kth largest element.

Input:
arr = [3, 2, 1, 5, 6, 4]
k = 2

Output:
5

Explanation:
Sorted:
[1,2,3,4,5,6]

2nd largest = 5
*/

/*
10. Find Kth Smallest After Sorting

Return the kth smallest element.

Input:
arr = [7, 10, 4, 3, 20, 15]
k = 3

Output:
7

Explanation:
Sorted:
[3,4,7,10,15,20]

3rd smallest = 7
*/

