/*
========================================
DUPLICATE, UNIQUE & MISSING NUMBER PROBLEMS
========================================
*/

/*
1. Check Duplicates

Return true if the array contains
any duplicate element.

Input:
[1, 2, 3, 1]

Output:
true

Input:
[1, 2, 3, 4]

Output:
false
*/

/*
2. Count Duplicate Elements

Count how many distinct elements
appear more than once.

Input:
[1, 2, 2, 3, 3, 3, 4]

Output:
2

Explanation:
Duplicates:
2, 3
*/

/*
3. Print Duplicate Elements

Return all elements that appear
more than once.

Input:
[1, 2, 2, 3, 3, 4, 5]

Output:
[2, 3]
*/

/*
4. First Duplicate Element

Return the first duplicate element
encountered while traversing.

Input:
[2, 1, 3, 5, 3, 2]

Output:
3
*/

/*
5. Last Duplicate Element

Return the last duplicate element
encountered while traversing.

Input:
[1, 2, 3, 2, 4, 1]

Output:
1
*/

/*
6. Remove Duplicates

Remove duplicate elements
while preserving order.

Input:
[1, 2, 2, 3, 1, 4]

Output:
[1, 2, 3, 4]
*/

/*
7. Count Unique Elements

Return the number of unique elements.

Input:
[1, 2, 2, 3, 3, 4]

Output:
4

Explanation:
Unique values:
1,2,3,4
*/

/*
8. Find Repeated Number

One number appears multiple times.

Return the repeated number.

Input:
[1, 3, 4, 2, 2]

Output:
2
*/

/*
9. Missing Number (1 To N)

Array contains numbers from 1 to N
with one missing number.

Input:
[1, 2, 4, 5]

Output:
3
*/

/*
10. Find Unique Element

Every element appears twice
except one.

Return the unique element.

Input:
[4, 1, 2, 1, 2]

Output:
4
*/

