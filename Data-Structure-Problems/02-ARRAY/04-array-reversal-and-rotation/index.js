/*
========================================
ARRAY REVERSAL & ROTATION PROBLEMS
========================================
*/

/*
1. Reverse Array

Reverse the entire array.

Input:
[1, 2, 3, 4, 5]

Output:
[5, 4, 3, 2, 1]
*/

/*
2. Reverse First K Elements

Reverse only the first K elements.

Input:
arr = [1, 2, 3, 4, 5]
k = 3

Output:
[3, 2, 1, 4, 5]
*/

/*
3. Reverse Last K Elements

Reverse only the last K elements.

Input:
arr = [1, 2, 3, 4, 5]
k = 3

Output:
[1, 2, 5, 4, 3]
*/

/*
4. Left Rotate By 1

Move every element one position left.

Input:
[1, 2, 3, 4, 5]

Output:
[2, 3, 4, 5, 1]
*/

/*
5. Right Rotate By 1

Move every element one position right.

Input:
[1, 2, 3, 4, 5]

Output:
[5, 1, 2, 3, 4]
*/

/*
6. Left Rotate By K

Rotate the array left by K positions.

Input:
arr = [1, 2, 3, 4, 5]
k = 2

Output:
[3, 4, 5, 1, 2]
*/

/*
7. Right Rotate By K

Rotate the array right by K positions.

Input:
arr = [1, 2, 3, 4, 5]
k = 2

Output:
[4, 5, 1, 2, 3]
*/

/*
8. Reverse String

Reverse the given string.

Input:
"hello"

Output:
"olleh"
*/

/*
9. Move Last Element To Front

Move the last element to the beginning.

Input:
[1, 2, 3, 4, 5]

Output:
[5, 1, 2, 3, 4]
*/

/*
10. Move First Element To End

Move the first element to the end.

Input:
[1, 2, 3, 4, 5]

Output:
[2, 3, 4, 5, 1]
*/

