/*
========================================
DECODE STRING PATTERN PROBLEMS
========================================
*/

/*
1. Decode String

Input:
"3[a]"

Output:
"aaa"
*/

/*
2. Nested Decode String

Input:
"3[a2[b]]"

Output:
"abbabbabb"
*/

/*
3. Multiple Encoded Parts

Input:
"2[abc]3[cd]ef"

Output:
"abcabccdcdcdef"
*/

/*
4. Decode Multi-Digit Count

Input:
"10[a]"

Output:
"aaaaaaaaaa"
*/

/*
5. Deeply Nested Decode

Input:
"2[a2[b3[c]]]"

Output:
"abcccbcccabcccbccc"
*/